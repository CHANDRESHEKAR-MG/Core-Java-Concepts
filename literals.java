class literals{
    public static void main(String[] args) {
        int num=0b011;
        int num1=0x7E;
        int num2=10_00_00_000;
        double num3=12e3;
        char c='a';
        c++;
        System.out.println(num3);
        System.out.println(num);
        System.out.println(num1);
        System.out.println(num2);
        System.out.println(c);
        }
    }